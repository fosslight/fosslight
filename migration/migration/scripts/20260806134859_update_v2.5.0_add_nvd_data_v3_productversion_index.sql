	`TYPE` VARCHAR(30) NOT NULL COMMENT 'Metrics system type (e.g., CVSS_V4, CVSS_V3, CVSS_V2, Ubuntu, Android)' COLLATE 'utf8mb4',
	`SCORE` LONGTEXT NOT NULL COMMENT 'Calculated numeric score string or raw text rating' COLLATE 'utf8mb4',
	PRIMARY KEY (`ID`, `PACKAGE_NAME`, `ECOSYSTEM`, `SOURCE`, `TYPE`) USING BTREE
) COLLATE='utf8mb4' ENGINE=InnoDB;

