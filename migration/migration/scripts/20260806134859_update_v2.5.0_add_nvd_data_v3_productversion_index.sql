CREATE TABLE `OSV_VULNERABILITIES` (
	`ID` INT(11) NOT NULL AUTO_INCREMENT,
	`OSV_ID` VARCHAR(50) NOT NULL COMMENT 'Unique OSV Identifier (e.g., CVE-2021-3114, GHSA-vp9c-fpxx-744v)' COLLATE 'utf8mb4',
	`SCHEMA_VERSION` VARCHAR(20) NULL DEFAULT NULL COMMENT 'OSV Schema Version' COLLATE 'utf8mb4',
	`SUMMARY` LONGTEXT NULL DEFAULT NULL COMMENT 'Short summary or title (under 120 characters)' COLLATE 'utf8mb4',
	`DETAILS` LONGTEXT NULL DEFAULT NULL COMMENT 'Detailed technical description of the vulnerability' COLLATE 'utf8mb4',
	`PUBL_DATE` DATETIME NULL DEFAULT NULL COMMENT 'Initial publication date',
	`MODI_DATE` DATETIME NULL DEFAULT NULL COMMENT 'Last modification date',
	`WITHDRAWN` DATETIME NULL DEFAULT NULL COMMENT 'Withdrawal date (If present, exclude from OSS matching filters)',
	`RAW_JSON` LONGTEXT NULL DEFAULT NULL COMMENT 'Full fallback JSON string containing references, credits, database_specific, etc.' COLLATE 'utf8mb4',
	PRIMARY KEY (`ID`) USING BTREE,
	UNIQUE INDEX `OSV_ID` (`OSV_ID`) USING BTREE,
	INDEX `WITHDRAWN` (`WITHDRAWN`) USING BTREE
) COLLATE='utf8mb4' ENGINE=InnoDB;

