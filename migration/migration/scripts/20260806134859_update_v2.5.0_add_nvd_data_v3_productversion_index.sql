	`RANGE_IDX` INT(11) NOT NULL COMMENT 'Array element sequence index within the package definition',
	`RANGE_TYPE` VARCHAR(20) NOT NULL COMMENT 'Version comparison format (SEMVER, ECOSYSTEM, GIT)' COLLATE 'utf8mb4',
	`REPO` LONGTEXT NULL DEFAULT NULL COMMENT 'Git repository URL (Required for GIT type)' COLLATE 'utf8mb4',
	`INTRODUCED` VARCHAR(50) NULL DEFAULT '0' COMMENT 'Lower bound version (0 means from the beginning of time)' COLLATE 'utf8mb4',
	`FIXED` LONGTEXT NULL DEFAULT NULL COMMENT 'Upper bound version where the issue is resolved (Exclusive)' COLLATE 'utf8mb4',
	`LAST_AFFECTED` VARCHAR(50) NULL DEFAULT NULL COMMENT 'Maximum affected version string (Inclusive)' COLLATE 'utf8mb4',
	`LIMIT_VERSION` VARCHAR(50) NULL DEFAULT '*' COMMENT 'Upper constraint boundary (* means infinity)' COLLATE 'utf8mb4',
	PRIMARY KEY (`ID`, `PACKAGE_IDX`, `RANGE_IDX`) USING BTREE,
	INDEX `RANGE_TYPE` (`RANGE_TYPE`) USING BTREE,
	INDEX `REPO` (`REPO`(768)) USING BTREE,
	INDEX `IDX_RANGES_PERF` (`ID`, `PACKAGE_IDX`, `RANGE_IDX`) USING BTREE
) COLLATE='utf8mb4' ENGINE=InnoDB;

